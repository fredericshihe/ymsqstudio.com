CREATE OR REPLACE FUNCTION public.get_weekly_decline_leaderboard(
  p_week_monday DATE DEFAULT DATE_TRUNC('week', NOW() AT TIME ZONE 'Asia/Shanghai')::DATE
)
RETURNS TABLE (
  board                  TEXT,
  rank_no                INTEGER,
  student_name           TEXT,
  student_major          TEXT,
  student_grade          TEXT,
  display_score          NUMERIC,
  alpha                  NUMERIC,
  trend_score            NUMERIC,
  mean_duration          NUMERIC,
  record_count           INTEGER,
  recent10_outlier_rate  NUMERIC,
  recent10_mean_dur      NUMERIC,
  recent10_count         INTEGER,
  target_minutes         NUMERIC,
  completed_minutes      NUMERIC,
  completion_ratio       NUMERIC,
  shortfall_minutes      NUMERIC,
  week_session_count     INTEGER
)
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = public
AS $function$
WITH week_context AS (
  SELECT
    COALESCE(p_week_monday, DATE_TRUNC('week', NOW() AT TIME ZONE 'Asia/Shanghai')::DATE) AS monday,
    (NOW() AT TIME ZONE 'Asia/Shanghai')::DATE AS today,
    CASE
      WHEN (NOW() AT TIME ZONE 'Asia/Shanghai')::DATE < COALESCE(p_week_monday, DATE_TRUNC('week', NOW() AT TIME ZONE 'Asia/Shanghai')::DATE)
        THEN 0
      WHEN (NOW() AT TIME ZONE 'Asia/Shanghai')::DATE >= COALESCE(p_week_monday, DATE_TRUNC('week', NOW() AT TIME ZONE 'Asia/Shanghai')::DATE) + 5
        THEN 5
      ELSE EXTRACT(DOW FROM (NOW() AT TIME ZONE 'Asia/Shanghai')::DATE)::INTEGER
    END AS elapsed_workdays
),
current_students AS (
  SELECT DISTINCT ON (sd.name)
    sb.student_name,
    COALESCE(NULLIF(BTRIM(sd.major), ''), sb.student_major) AS student_major,
    COALESCE(NULLIF(BTRIM(sd.grade), ''), sb.student_grade) AS student_grade,
    sb.alpha,
    sb.mean_duration,
    sb.record_count
  FROM public.student_database sd
  JOIN public.student_baseline sb ON sb.student_name = sd.name
  WHERE COALESCE(sd.archived, FALSE) IS FALSE
    AND NULLIF(BTRIM(sd.name), '') IS NOT NULL
  ORDER BY sd.name, sd.updated_at DESC NULLS LAST, sd.id DESC
),
targeted_students AS (
  SELECT
    cs.*,
    wc.monday AS week_monday,
    metrics.period_start,
    metrics.record_count AS period_record_count,
    EXISTS (
      SELECT 1
      FROM public.score_semesters ss
      WHERE ss.started_at = public.get_score_semester_start(
        CASE
          WHEN wc.monday = DATE_TRUNC('week', NOW() AT TIME ZONE 'Asia/Shanghai')::DATE
            THEN NOW()
          ELSE (((wc.monday + 7)::TIMESTAMP) AT TIME ZONE 'Asia/Shanghai')
        END
      )
        AND COALESCE(ss.week_target_snapshot, '{}'::JSONB) ? cs.student_name
    ) AS has_saved_target,
    progress.week_target_minutes AS target_minutes,
    progress.settled_week_minutes AS completed_minutes,
    progress.pace_completion_ratio AS completion_ratio,
    progress.expected_to_date_minutes AS expected_minutes,
    progress.shortfall_to_pace_minutes AS shortfall_minutes,
    progress.settled_session_count AS week_session_count,
    progress.elapsed_workdays
  FROM current_students cs
  CROSS JOIN week_context wc
  CROSS JOIN LATERAL public.get_student_score_period_metrics(cs.student_name, wc.monday) metrics
  CROSS JOIN LATERAL public.get_student_week_progress_context(
    cs.student_name,
    wc.monday,
    NULL
  ) progress
),
eligible AS (
  SELECT ts.*
  FROM targeted_students ts
  WHERE ts.week_session_count > 0
    AND ts.elapsed_workdays > 0
    -- 老生沿用已保存的周目标；新生首个活跃周不扣币，至少完成一个
    -- 完整周后且当前周有 3 次有效记录，才进入缩水榜。
    AND (
      ts.has_saved_target
      OR (
        DATE_TRUNC('week', ts.period_start AT TIME ZONE 'Asia/Shanghai')::DATE < ts.week_monday
        AND ts.week_session_count >= 3
      )
    )
),
ranked AS (
  SELECT
    ROW_NUMBER() OVER (
      ORDER BY completion_ratio ASC,
               shortfall_minutes DESC,
               completed_minutes ASC,
               student_name ASC
    )::INTEGER AS rank_no,
    e.*
  FROM eligible e
  WHERE e.completion_ratio < 0.70
)
SELECT
  '缩水榜'::TEXT,
  r.rank_no,
  r.student_name,
  r.student_major,
  r.student_grade,
  ROUND((r.completion_ratio * 100)::NUMERIC, 1),
  r.alpha,
  NULL::NUMERIC,
  r.mean_duration,
  r.period_record_count::INTEGER,
  NULL::NUMERIC,
  NULL::NUMERIC,
  NULL::INTEGER,
  ROUND(r.target_minutes, 2),
  ROUND(r.completed_minutes, 2),
  ROUND(r.completion_ratio, 4),
  ROUND(r.shortfall_minutes, 2),
  r.week_session_count
FROM ranked r
ORDER BY r.rank_no;
$function$;

