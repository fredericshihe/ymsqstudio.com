CREATE OR REPLACE FUNCTION public.start_new_semester(p_confirm TEXT)
RETURNS TEXT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_count         INTEGER;
  v_total_cleared INTEGER;
  v_started_at    TIMESTAMPTZ;
  v_week_monday   DATE;
  v_target_snapshot JSONB;
BEGIN
  IF p_confirm <> 'CONFIRM_NEW_SEMESTER' THEN
    RETURN '❌ 安全确认失败。请传入字符串 "CONFIRM_NEW_SEMESTER" 方可执行。';
  END IF;

  v_started_at := clock_timestamp();
  v_week_monday := DATE_TRUNC('week', v_started_at AT TIME ZONE 'Asia/Shanghai')::DATE;

  -- 先保存已有老生目标，再建立新学期边界；新生不写入快照，后续按同教研室
  -- 平均目标或默认 270 分钟冷启动。
  v_target_snapshot := public.capture_score_semester_targets(v_started_at);

  INSERT INTO public.score_semesters (started_at, source, week_target_snapshot)
  VALUES (
    v_started_at,
    'manual_semester_reset',
    v_target_snapshot
  )
  ON CONFLICT (started_at) DO NOTHING;

  INSERT INTO public.student_coins (student_name, balance, semester_earned)
  SELECT sd.name, 0, 0
  FROM public.student_database sd
  ON CONFLICT (student_name) DO NOTHING;

  INSERT INTO public.coin_transactions (
    student_name,
    amount,
    balance_after,
    reason,
    transaction_type
  )
  SELECT
    sc.student_name,
    -sc.balance,
    0,
    '开启新学期：清空音符币余额（原余额 ' || sc.balance || '，本学期累计 '
      || sc.semester_earned || '）。',
    'semester_reset'
  FROM public.student_coins sc
  ORDER BY sc.student_name;
  GET DIAGNOSTICS v_count = ROW_COUNT;

  SELECT COALESCE(SUM(GREATEST(sc.balance, 0)), 0)
  INTO v_total_cleared
  FROM public.student_coins sc;

  UPDATE public.student_coins
  SET
    balance = 0,
    semester_earned = 0,
    updated_at = NOW()
  WHERE student_name IS NOT NULL;

  PERFORM set_config('app.skip_score_trigger', 'on', true);
  PERFORM set_config('app.computing_score', 'true', true);

  UPDATE public.student_score_history h
  SET
    composite_score = 0,
    raw_score = 0.0,
    baseline_score = NULL,
    trend_score = NULL,
    momentum_score = NULL,
    accum_score = NULL,
    outlier_rate = 0.0,
    short_session_rate = 0.0,
    mean_duration = 0.0,
    record_count = 0
  WHERE h.snapshot_date = v_week_monday;

  UPDATE public.student_baseline sb
  SET
    composite_score = 0,
    raw_score = 0.0,
    baseline_score = NULL,
    trend_score = NULL,
    momentum_score = NULL,
    accum_score = NULL,
    w_score = 0.0,
    score_confidence = 0.0,
    growth_velocity = 0.0,
    weeks_improving = 0,
    last_updated = NOW()
  WHERE sb.student_name IS NOT NULL;

  PERFORM set_config('app.computing_score', 'false', true);
  PERFORM set_config('app.skip_score_trigger', 'off', true);

  RETURN '✅ 新学期已开启，共清空 ' || v_count || ' 位学生的音符币余额，合计清空 '
    || v_total_cleared || ' 枚；评分历史已从本学期边界重新起算。';
END;
$function$;

REVOKE ALL ON FUNCTION public.start_new_semester(TEXT) FROM PUBLIC;
